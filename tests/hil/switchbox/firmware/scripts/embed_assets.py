"""PlatformIO pre-build step: embed the API spec, the board description and the web UI in flash.

Reads ../openapi.json (the single source of truth, also read by the Python client and the offline
tests), the board profiles the env selects (../boards; platformio.ini custom_carrier_profile,
custom_feather_profile, custom_target_profile) and ui/index.html, and writes src/generated/assets.h:
  SPEC_JSON / SPEC_JSON_LEN     the spec minified to one line (it is also a serial reply line)
  BOARD_JSON / BOARD_JSON_LEN   GET /api/board: profiles plus the derived terminal map, one line
  UI_HTML / UI_HTML_LEN         the page served at /, with the Wiring view's SVGs drawn by
                                ../tools/render_pinout.py from the same profiles
  SB_API_VERSION                the spec's info.version
  SB_SPEC_SHA256                SHA-256 of the minified spec; getInfo reports it, so a client can
                                check the board serves the same spec as its checkout
  SB_BOARD_ID                   "<carrier>/<feather>"
The build fails if the profiles do not validate (render_pinout.validate). Minified the same way as
tinyg_hil.switchbox.spec_digest(): json.dumps(separators=(",", ":"), ensure_ascii=False), key order
preserved. The output file is only rewritten when its content changes.
"""
import hashlib
import json
import pathlib
import sys

try:
    Import("env")                     # provided by SCons when PlatformIO runs this script
    PROJECT = pathlib.Path(env.subst("$PROJECT_DIR"))
    option = env.GetProjectOption
except NameError:                     # run directly: python scripts/embed_assets.py
    PROJECT = pathlib.Path(__file__).resolve().parent.parent

    def option(name, default=None):
        return default

SWITCHBOX = PROJECT.parent
SPEC = SWITCHBOX / "openapi.json"
UI = PROJECT / "ui" / "index.html"
OUT = PROJECT / "src" / "generated" / "assets.h"
PLACEHOLDERS = {"board": "<!--WIRING_BOARD-->", "tinyg": "<!--WIRING_TINYG-->", "legend": "<!--WIRING_LEGEND-->"}


def c_bytes(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 20]) for i in range(0, len(data), 20)]
    body = ",\n    ".join(rows)
    return (f"static const char {name}[] PROGMEM = {{\n    {body}\n}};\n"
            f"static const size_t {name}_LEN = {len(data)};\n")


def minify(obj):
    return json.dumps(obj, separators=(",", ":"), ensure_ascii=False).encode("utf-8")


def main():
    sys.path.insert(0, str(SWITCHBOX / "tools"))
    import render_pinout
    carrier = option("custom_carrier_profile", "terminal-block-featherwing")
    feather = option("custom_feather_profile", "huzzah-esp8266")
    target = option("custom_target_profile", "tinyg-v8")
    boards = render_pinout.load(carrier, feather, target)
    problems = render_pinout.validate(boards, render_pinout.terminal_map(boards), render_pinout.default_channels())
    if problems:
        raise SystemExit("embed_assets: board profiles do not validate:\n  " + "\n  ".join(problems))

    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    mini = minify(spec)
    board = minify(render_pinout.board_json(boards))
    ui = UI.read_text(encoding="utf-8")
    for key, svg in render_pinout.ui_fragments(boards).items():
        assert PLACEHOLDERS[key] in ui, PLACEHOLDERS[key]
        ui = ui.replace(PLACEHOLDERS[key], svg)
    ui = ui.encode("utf-8")
    text = ("// Generated by scripts/embed_assets.py from ../openapi.json, ../boards and ui/index.html. Do not edit.\n"
            "#pragma once\n#include <pgmspace.h>\n#include <stddef.h>\n\n"
            f"#define SB_API_VERSION \"{spec['info']['version']}\"\n"
            f"#define SB_SPEC_SHA256 \"{hashlib.sha256(mini).hexdigest()}\"\n"
            f"#define SB_BOARD_ID \"{carrier}/{feather}\"\n\n"
            + c_bytes("SPEC_JSON", mini) + "\n" + c_bytes("BOARD_JSON", board) + "\n" + c_bytes("UI_HTML", ui))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    if not OUT.exists() or OUT.read_text() != text:
        OUT.write_text(text)
        print(f"embed_assets: spec {len(mini)} B, board {len(board)} B ({carrier}/{feather}), ui {len(ui)} B "
              f"-> {OUT.relative_to(PROJECT)}")


main()
